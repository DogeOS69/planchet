#!/usr/bin/env python3
"""Independent, deterministic test oracle; not used by the guest/build.

SHA-256/RIPEMD-160 use Python's standard hashlib. Keccak-f[1600] below
uses only Python integer arithmetic and is checked against the published
empty/abc Keccak-256 vectors. ECDSA uses the defining equation with d=k=1;
these public test scalars MUST NEVER be used to sign anything valuable.
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MASK = (1 << 64) - 1
ROT = ((0, 36, 3, 41, 18), (1, 44, 10, 45, 2),
       (62, 6, 43, 15, 61), (28, 55, 25, 21, 56), (27, 20, 39, 8, 14))
RC = (0x0000000000000001, 0x0000000000008082, 0x800000000000808A,
      0x8000000080008000, 0x000000000000808B, 0x0000000080000001,
      0x8000000080008081, 0x8000000000008009, 0x000000000000008A,
      0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
      0x000000008000808B, 0x800000000000008B, 0x8000000000008089,
      0x8000000000008003, 0x8000000000008002, 0x8000000000000080,
      0x000000000000800A, 0x800000008000000A, 0x8000000080008081,
      0x8000000000008080, 0x0000000080000001, 0x8000000080008008)


def rol(x, n):
    return ((x << n) | (x >> ((64 - n) % 64))) & MASK


def keccak(data):
    padded = bytearray(data) + b'\x01'
    padded.extend(bytes((-len(padded)) % 136))
    padded[-1] |= 0x80
    a = [0] * 25
    for start in range(0, len(padded), 136):
        for i in range(17):
            a[i] ^= int.from_bytes(padded[start + i * 8:start + i * 8 + 8], 'little')
        for rc in RC:
            c = [a[x] ^ a[x + 5] ^ a[x + 10] ^ a[x + 15] ^ a[x + 20] for x in range(5)]
            d = [c[(x - 1) % 5] ^ rol(c[(x + 1) % 5], 1) for x in range(5)]
            a = [v ^ d[i % 5] for i, v in enumerate(a)]
            b = [0] * 25
            for x in range(5):
                for y in range(5):
                    b[y + 5 * ((2 * x + 3 * y) % 5)] = rol(a[x + 5 * y], ROT[x][y])
            a = [b[x + 5 * y] ^ ((~b[(x + 1) % 5 + 5 * y]) & b[(x + 2) % 5 + 5 * y])
                 for y in range(5) for x in range(5)]
            a[0] ^= rc
    return b''.join(v.to_bytes(8, 'little') for v in a)[:32]


def sha(data):
    return hashlib.sha256(data).digest()


def double(data):
    return sha(sha(data))


assert keccak(b'').hex() == 'c5d2460186f7233c927e7db2dcc703c0e500b653ca82273b7bfad8045d85a470'
assert keccak(b'abc').hex() == '4e03657aea45a94fc7d47ba826c8d667c0d1e6e33a64a036ec44f58fa12d6c45'

lines = ['// Generated by scripts/generate-fixtures.py; do not edit by hand.', 'use hex_literal::hex;']


def constant(name, data):
    lines.append(f'pub const {name}: [u8; {len(data)}] = hex!("{data.hex()}");')


transcript = bytearray()
sha_cases = [(b'', 0), (b'abc', 3)] + [(bytes([0xa3]) * n, n) for n in (55, 56, 63, 64, 65, 135, 136, 137, 1024)]
lines.append('pub const SHA_CASES: &[(usize, [u8; 32], [u8; 32])] = &[')
for data, n in sha_cases:
    s, d = sha(data), double(data)
    lines.append(f'    ({n}, hex!("{s.hex()}"), hex!("{d.hex()}")),')
    transcript.extend(s + d)
lines.append('];')
lines.append('pub const KECCAK_CASES: &[(usize, [u8; 32])] = &[')
for data in (b'', b'abc', *(bytes([0xa3]) * n for n in (135, 136, 137, 200))):
    k = keccak(data)
    lines.append(f'    ({len(data)}, hex!("{k.hex()}")),')
    transcript.extend(k)
lines.append('];')

curves = (
    ('K256', '79be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798',
     '483ada7726a3c4655da4fbfc0e1108a8fd17b448a68554199c47d08ffb10d4b8',
     'fffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141'),
    ('P256', '6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296',
     '4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5',
     'ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551'),
)
constant('PREHASH', sha(b'abc'))
for name, x, y, order in curves:
    n = int(order, 16)
    r = int(x, 16) % n
    s = (int.from_bytes(sha(b'abc'), 'big') + r) % n
    s = min(s, n - s)
    constant(name + '_SEC1', b'\x04' + bytes.fromhex(x + y))
    constant(name + '_COMPRESSED', bytes([2 + (int(y, 16) & 1)]) + bytes.fromhex(x))
    constant(name + '_SIGNATURE', r.to_bytes(32, 'big') + s.to_bytes(32, 'big'))

hash160 = hashlib.new('ripemd160', sha(bytes.fromhex('0279be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798'))).digest()
constant('HASH160', hash160)
transcript.extend(hash160)
genesis = (ROOT / 'fixtures/mainnet-genesis.bin').read_bytes()
txid, block_id = double(genesis[81:]), double(genesis[:80])
assert txid[::-1].hex() == '5b2a3f53f605d62c53e62932dac6925e3d74afa5a4b459745c36d42d0ed26a69'
assert block_id[::-1].hex() == '1a91e3dace36e2be3bf030a65679fe821aa1d6ef92e7c9902eb318182c355691'
constant('GENESIS_TXID', txid)
constant('GENESIS_BLOCK_ID', block_id)
transcript.extend(txid + block_id)
leaves = [double(b'leaf' + bytes([ord('0') + i])) for i in range(3)]
lines.append('pub const LEAVES: [[u8; 32]; 3] = [' + ', '.join(f'hex!("{leaf.hex()}")' for leaf in leaves) + '];')
root = double(double(leaves[0] + leaves[1]) + double(leaves[2] + leaves[2]))
constant('MERKLE_ROOT', root)
transcript.extend(root)
# Two successful checks of compressed/uncompressed keys and six rejection cases per curve.
transcript.extend(bytes([1]) * 16)
constant('TRANSCRIPT_SHA256', sha(transcript))
lines.append('')
path = ROOT / 'src/fixtures.rs'
path.write_text('\n'.join(lines))
print(f'{path}: {len(transcript)} transcript bytes, SHA256={sha(transcript).hex()}')
